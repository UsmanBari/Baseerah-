const URDU_DIGITS = ["۰", "۱", "۲", "۳", "۴", "۵", "۶", "۷", "۸", "۹"];

export function toUrduDigits(num) {
  if (num === null || num === undefined) return "";
  return String(num).replace(/\d/g, (d) => URDU_DIGITS[parseInt(d, 10)]);
}

export function t(key, lang = "ur") {
  const table = DICT[lang] || DICT.ur;
  return table[key] || DICT.en[key] || key;
}

/** Urdu companion label shown next to the English UI label (UI is English-first, bilingual). */
export function ur(key) {
  return (DICT.ur && DICT.ur[key]) || "";
}

/** "English" + small Urdu companion, e.g. Learn Namaz · نماز سیکھیں */
export function biLabel(key, urKey = key) {
  const u = ur(urKey);
  return `<span class="bi-en">${t(key, "en")}</span>${u ? `<span class="bi-ur" lang="ur" dir="rtl">${u}</span>` : ""}`;
}

export function applyI18n(container, lang = "ur") {
  const elements = container.querySelectorAll("[data-i18n]");
  elements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const val = t(key, lang);
    if (val) {
      if (el.tagName === "INPUT" && el.hasAttribute("placeholder")) {
        el.setAttribute("placeholder", val);
      } else {
        el.textContent = val;
      }
    }
  });
}
