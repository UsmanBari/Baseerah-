"""Build word statistics for tap-a-word and the vocabulary learner.

Everything comes from the app's own word-by-word data in data/surahs/
(Arabic words with Urdu and English meanings). Nothing is typed by hand.

Outputs:
  data/word_freq.js   window.BASEERAH_WORD_FREQ = { normalizedForm: count, ... }
                      (only forms that appear 2+ times; anything missing = 1)
  data/vocab.js       window.BASEERAH_VOCAB = { totalWords, words: [...] }
                      the most frequent word forms with their most common
                      Urdu/English meanings and the first place they appear.

The normalisation here must match normalizeArabic() in js/core/words.js.
"""
import json, re, glob, pathlib
from collections import Counter, defaultdict

ROOT = pathlib.Path(__file__).resolve().parent.parent
VOCAB_SIZE = 400

STRIP = re.compile(
    "[" "ؐ-ؚ" "ً-ٟ" "ٰ" "ۖ-ۭ" "ـ"
    "​-‏" "-" "]"
)
WAQF_TOKEN = re.compile(r"\s+[ۖ-ۭؕ-ؚ-]+")


def normalize(word):
    w = STRIP.sub("", word or "")
    w = re.sub("[آأإٱ]", "ا", w)    # alef forms -> ا
    w = w.replace("ی", "ي").replace("ى", "ي")  # ی ى -> ي
    w = w.replace("ک", "ك")                          # ک -> ك
    w = w.replace("ہ", "ه").replace("ھ", "ه")  # ہ ھ -> ه
    return re.sub(r"\s+", "", w)


def display_form(word):
    """Vocalised word without the pause marks that follow it."""
    return WAQF_TOKEN.sub("", word or "").strip()


counts = Counter()
meanings = defaultdict(Counter)
shapes = defaultdict(Counter)
meaning_keys = defaultdict(Counter)  # same meaning regardless of capitals
first_ref = {}
total = 0

for f in sorted(glob.glob(str(ROOT / "data/surahs/*.js"))):
    d = json.loads(re.sub(r"^window\.BASEERAH_SURAH\s*=\s*", "", open(f, encoding="utf-8").read()).rstrip().rstrip(";"))
    for a in d["ayahs"]:
        for i, w in enumerate(a["words"]):
            form = normalize(w["ar"])
            if not form:
                continue
            total += 1
            counts[form] += 1
            meanings[form][((w.get("ur") or "").strip(), (w.get("en") or "").strip())] += 1
            meaning_keys[form][((w.get("ur") or "").strip(), (w.get("en") or "").strip().lower())] += 1
            shapes[form][display_form(w["ar"])] += 1
            first_ref.setdefault(form, f"{d['number']}:{a['number']}")

freq = {k: v for k, v in counts.items() if v >= 2}
(ROOT / "data/word_freq.js").write_text(
    "/* AUTO-GENERATED by scripts/build_word_data.py from data/surahs. Counts of each word form in the Quran (forms seen once are omitted). */\n"
    "window.BASEERAH_WORD_FREQ = " + json.dumps(freq, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)

vocab = []
for form, c in counts.most_common(VOCAB_SIZE):
    top_keys = meaning_keys[form].most_common(2)
    pick = lambda key: next(m for m, _ in meanings[form].most_common() if (m[0], m[1].lower()) == key)
    top = [(pick(k), n) for k, n in top_keys]
    (ur, en), n1 = top[0]
    entry = {
        "f": form, "ar": shapes[form].most_common(1)[0][0], "n": c,
        "ur": ur, "en": en, "ref": first_ref[form],
    }
    # Same spelling can mean different things in different places: keep a second meaning if it's common.
    if len(top) > 1 and top[1][1] >= max(3, 0.2 * c) and top[1][0] != (ur, en):
        entry["ur2"], entry["en2"] = top[1][0]
    vocab.append(entry)

(ROOT / "data/vocab.js").write_text(
    "/* AUTO-GENERATED by scripts/build_word_data.py from data/surahs (word meanings: QuranWBW Urdu/English as used in the app). */\n"
    "window.BASEERAH_VOCAB = " + json.dumps({"totalWords": total, "words": vocab}, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
covered = sum(v["n"] for v in vocab)
print(f"words={total} forms={len(counts)} freq_entries={len(freq)} vocab={len(vocab)} covers={covered/total:.1%} (top 100 cover {sum(v['n'] for v in vocab[:100])/total:.1%})")
