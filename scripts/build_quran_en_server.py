"""Generate netlify/lib/quran-en.mjs: the English meaning of every ayah, for the
daily Quran notification ("In order" goes through the whole Quran, "Random"
picks any ayah).

Text is never typed by hand: it is read from the app's own sourced files in
data/surahs/ (Saheeh International via QuranEnc). Footnote markers like [1]
are removed because a notification can't show footnotes.
Run after changing the surah data.
"""
import json, re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
names, ayahs = [], []
for s in range(1, 115):
    raw = (root / f"data/surahs/{s:03d}.js").read_text(encoding="utf-8")
    data = json.loads(re.sub(r"^window\.BASEERAH_SURAH\s*=\s*", "", raw).rstrip().rstrip(";"))
    names.append(data.get("nameEn") or "")
    for a in data["ayahs"]:
        en = re.sub(r"\[\d+\]", "", a["en"] or "").strip()
        en = re.sub(r"\s{2,}", " ", en)
        ayahs.append([s, a["number"], en])

assert len(ayahs) == 6236, len(ayahs)
assert all(x[2] for x in ayahs), "empty translation"
body = "/* AUTO-GENERATED by scripts/build_quran_en_server.py from data/surahs/*.js (Saheeh International via QuranEnc). Do not edit by hand. */\n"
body += "export const SURAH_NAMES_EN = " + json.dumps(names, ensure_ascii=False) + ";\n"
body += "export default " + json.dumps(ayahs, ensure_ascii=False, separators=(",", ":")) + ";\n"
(root / "netlify/lib/quran-en.mjs").write_text(body, encoding="utf-8")
print("wrote", len(ayahs), "ayahs,", len(body.encode()) // 1024, "KB")
