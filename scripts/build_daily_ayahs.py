"""Generate netlify/lib/daily-ayahs.mjs for the daily "Quran time" notification.

Ayah text is never typed by hand: the English translation (Saheeh
International, via QuranEnc) is read from the app's own sourced files in
data/surahs/. Footnote markers like [1] are removed because a notification
can't show footnotes. Only ayahs short enough to show in full (<= 170
characters) are used, so a notification never cuts an ayah in the middle.
Run after changing the list below or the surah data.
"""
import json, re, pathlib

REFS = [
    # the app's featured ayahs
    *[(a["surah"], a["ayah"]) for a in json.loads((pathlib.Path(__file__).resolve().parent.parent / "data/featured_ayahs.json").read_text(encoding="utf-8"))],
    # about the Quran and recitation
    (54, 17), (17, 9), (38, 29), (10, 57), (29, 45),
    # remembrance, prayer, patience, hope
    (2, 152), (2, 186), (2, 45), (13, 28), (33, 41), (40, 60), (14, 7),
    (3, 139), (3, 200), (9, 51), (39, 53), (94, 5), (94, 6), (93, 3),
    (93, 5), (65, 3), (29, 69), (47, 7), (50, 16), (55, 13),
    (23, 118), (25, 74), (8, 46),
]

root = pathlib.Path(__file__).resolve().parent.parent
seen, out, skipped = set(), [], []
for s, a in REFS:
    if (s, a) in seen:
        continue
    seen.add((s, a))
    raw = (root / f"data/surahs/{s:03d}.js").read_text(encoding="utf-8")
    data = json.loads(re.sub(r"^window\.BASEERAH_SURAH\s*=\s*", "", raw).rstrip().rstrip(";"))
    ayah = next((x for x in data["ayahs"] if x["number"] == a), None)
    if not ayah:
        skipped.append((s, a, "missing")); continue
    en = re.sub(r"\[\d+\]", "", ayah["en"]).strip()
    en = re.sub(r"\s{2,}", " ", en)
    # The source sometimes closes a quote that opened in the previous ayah; drop a lone trailing quote.
    if en.count('"') % 2 == 1 and en.endswith('"'):
        en = en[:-1].rstrip()
    # Notifications show complete ayahs only: skip fragments that start or end mid-sentence.
    if en[-1:] in (",", "-", "–") or en[:1] == "[":
        skipped.append((s, a, "fragment")); continue
    if len(en) > 170:
        skipped.append((s, a, f"too long ({len(en)})")); continue
    out.append({"surah": s, "ayah": a, "surahNameEn": data.get("nameEn") or data.get("englishName") or "", "en": en})

body = "/* AUTO-GENERATED by scripts/build_daily_ayahs.py from data/surahs/*.js (Saheeh International via QuranEnc). Do not edit by hand. */\n"
body += "export default " + json.dumps(out, ensure_ascii=False, indent=2) + ";\n"
(root / "netlify/lib/daily-ayahs.mjs").write_text(body, encoding="utf-8")
print("wrote", len(out), "ayahs; skipped:", skipped)
